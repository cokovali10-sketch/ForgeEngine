//! forge-asset-tools — Rust tooling for ForgeEngine.
//!
//! Generates `generated_palette.h` (C++ header) from a named color palette.
//! Demonstrates the Rust <-> C++ bridge: Rust owns asset data, C++ consumes it.

use std::env;
use std::fs;
use std::path::Path;

struct PaletteEntry {
    name: &'static str,
    r: u8,
    g: u8,
    b: u8,
}

const PALETTE: &[PaletteEntry] = &[
    PaletteEntry { name: "Midnight", r: 16, g: 20, b: 30 },
    PaletteEntry { name: "Slate", r: 100, g: 116, b: 139 },
    PaletteEntry { name: "Sky", r: 56, g: 189, b: 248 },
    PaletteEntry { name: "Emerald", r: 52, g: 211, b: 153 },
    PaletteEntry { name: "Gold", r: 250, g: 204, b: 21 },
    PaletteEntry { name: "Crimson", r: 220, g: 38, b: 38 },
    PaletteEntry { name: "Cloud", r: 241, g: 245, b: 249 },
];

const HEADER_GUARD: &str = "FORGE_GENERATED_PALETTE_H";

fn main() {
    let out = env::args()
        .nth(1)
        .unwrap_or_else(|| "generated_palette.h".to_string());

    let mut lines = String::new();
    lines.push_str(&format!("// Auto-generated by forge-asset-tools. Do not edit.\n"));
    lines.push_str(&format!("#ifndef {HEADER_GUARD}\n#define {HEADER_GUARD}\n\n"));
    lines.push_str("#include \"forge/math/rect.h\"\n\n");
    lines.push_str("namespace forge::assets {\n\n");

    for entry in PALETTE {
        let (r, g, b) = (entry.r, entry.g, entry.b);
        lines.push_str(&format!(
            "constexpr Color {} = Color{{{:.4}f, {:.4}f, {:.4}f}};\n",
            entry.name.to_lowercase(),
            r as f32 / 255.0,
            g as f32 / 255.0,
            b as f32 / 255.0,
        ));
    }

    lines.push_str("\n}  // namespace forge::assets\n\n");
    lines.push_str(&format!("#endif  // {HEADER_GUARD}\n"));

    let path = Path::new(&out);
    fs::write(path, lines).expect("failed to write generated header");
    println!("wrote {} with {} palette entries", path.display(), PALETTE.len());
}